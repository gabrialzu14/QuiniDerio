const fs=require('node:fs');
const assert=require('node:assert/strict');
const ts=require('typescript');
require.extensions['.ts']=(module,filename)=>module._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2017}}).outputText,filename);
const {validateDetails,kickoffUtc,mergeFixtures,matchDetails,standing}=require('../app/lib/match-details.ts');
const row={round:3,team:'Derio A',opponent:'Touring',is_home:false,scheduled_at:'2026-10-17T14:30:00Z',fixture_details:null};
const details=matchDetails(row);
assert.equal(details.date,'17/10/2026');assert.equal(details.time,'16:30');assert.equal(details.derioPoints,12);assert.equal(details.opponentPoints,8);
assert.equal(kickoffUtc('17/10/2026','16:30'),'2026-10-17T14:30:00.000Z');
assert.equal(kickoffUtc('17/12/2026','16:30'),'2026-12-17T15:30:00.000Z');
assert.throws(()=>kickoffUtc('31/02/2026','16:30'));
assert.throws(()=>kickoffUtc('29/03/2026','02:30'));
assert.throws(()=>validateDetails({...details,derioPosition:0}));
assert.throws(()=>validateDetails({...details,opponentPoints:1.5}));
assert.throws(()=>validateDetails({...details,derioForm:'ABCDE'}));
assert.throws(()=>validateDetails({...details,opponent:' '}));
const changed=validateDetails({...details,teamLabel:'CD Derio A',opponent:'Nuevo rival',venue:'Campo nuevo',location:'Derio',derioPoints:0,derioForm:'vEd',opponentPosition:null});
assert.equal(changed.derioForm,'VED');assert.equal(changed.derioPoints,0);
const f=mergeFixtures([{...row,opponent:changed.opponent,fixture_details:changed}])[3]['Derio A'];
assert.equal(f.teamLabel,'CD Derio A');assert.equal(f.opponent,'Nuevo rival');assert.equal(f.venue,'Campo nuevo, Derio');assert.equal(f.isHome,false);assert.equal(f.derioPoints,0);assert.equal(f.opponentPosition,null);
assert.equal(standing(3,0),'3º · 0 pts');assert.equal(standing(null,null),'');
assert.equal(require('../app/lib/quiz-fixtures.ts').quizFixtures[3]['Derio A'].opponent,'Touring');
console.log('Passed: defaults, edit/read roundtrip, zero points, validation, Madrid summer/winter time, invalid DST time, immutable fixtures.');
