const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const ts=require("typescript");
const read=p=>fs.readFileSync(path.resolve(__dirname,"..",p),"utf8");
const tsSource=read("app/lib/weekend-boundary.ts");
const compiled=ts.transpileModule(tsSource,{compilerOptions:{target:ts.ScriptTarget.ES2021,module:ts.ModuleKind.CommonJS}}).outputText;
const context={exports:{},Date,Number};
vm.runInNewContext(compiled,context);
const locate=context.exports.saturdaySundayBoundary;
assert.equal(typeof locate,"function");
const game=(date,status="scheduled")=>({date,status});
assert.equal(locate([game("31/10/2026"),game("01/11/2026")]),1);
assert.equal(locate([game("31/10/2026"),game("31/10/2026"),game("01/11/2026"),game("01/11/2026")]),2);
assert.equal(locate([game("30/10/2026"),game("31/10/2026"),game("01/11/2026")]),2);
assert.equal(locate([game("31/10/2026"),game("31/10/2026")]),-1);
assert.equal(locate([game("01/11/2026"),game("01/11/2026")]),-1);
assert.equal(locate([game("30/10/2026"),game("01/11/2026")]),-1);
assert.equal(locate([game("24/10/2026"),game("01/11/2026")]),-1);
assert.equal(locate([game("31/02/2026"),game("01/03/2026")]),-1);
assert.equal(locate([game("31/10/2026","rest"),game("01/11/2026")]),-1);
assert.equal(locate([game("31/10/2026"),game(undefined),game("01/11/2026")]),-1);
const page=read("app/page.tsx"),css=read("app/sections.css");
assert.match(page,/const weekendBoundaryIndex=saturdaySundayBoundary\(homeGames\)/);
assert.match(page,/index===weekendBoundaryIndex\?" qdWeekendBoundaryStart"/);
assert.match(page,/index===weekendBoundaryIndex-1\?" qdWeekendBoundaryEnd"/);
assert.match(css,/\.qdFixture\.qdWeekendBoundaryStart::before\{[\s\S]*?height:2px!important;[\s\S]*?background:#fff!important/);
assert.match(css,/\.qdFixture\.qdWeekendBoundaryEnd\{\s*border-bottom:0!important/);
console.log("Passed: date-driven Saturday/Sunday markers, DST safety, no false weekend separators, white line.");
